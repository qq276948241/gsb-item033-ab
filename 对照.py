#!/usr/bin/env python3
# 对照：直接调用降雨.py，逐字核对真输出。不另写分级。
import os
import subprocess
import sys

脚本目录 = os.path.dirname(os.path.abspath(__file__))
降雨脚本 = os.path.join(脚本目录, "降雨.py")

缺数据错 = "没法报雨：缺了降雨量\n"
负数错 = "没法报雨：降雨量不能是负的\n"
格式错 = "没法报雨：请给出一个不小于零的整数降雨量\n"

# 每条：名字、传给降雨.py的参数、期望退出码、期望标准输出、期望标准错误
用例 = [
    ("一段都没有", [], 2, "", 缺数据错),
    ("写成缺", ["缺"], 2, "", 缺数据错),
    ("给了两段", ["1", "2"], 2, "", 缺数据错),
    ("空的一段", [""], 2, "", 缺数据错),
    ("0是小雨", ["0"], 0, "小雨\n", ""),
    ("正好9仍是小雨", ["9"], 0, "小雨\n", ""),
    ("前导零09按数值算", ["09"], 0, "小雨\n", ""),
    ("正好10升成中雨", ["10"], 0, "中雨\n", ""),
    ("正好24仍是中雨", ["24"], 0, "中雨\n", ""),
    ("正好25升成大雨", ["25"], 0, "大雨\n", ""),
    ("正好49仍是大雨", ["49"], 0, "大雨\n", ""),
    ("正好50升成暴雨", ["50"], 0, "暴雨\n", ""),
    ("51也是暴雨", ["51"], 0, "暴雨\n", ""),
    ("负数-5", ["-5"], 2, "", 负数错),
    ("带小数3.5", ["3.5"], 2, "", 格式错),
    ("带正号+5", ["+5"], 2, "", 格式错),
    ("夹了字abc", ["abc"], 2, "", 格式错),
]


def 跑一次(参数):
    成品 = subprocess.run(
        [sys.executable, 降雨脚本, *参数],
        capture_output=True,
        text=True,
    )
    return 成品.returncode, 成品.stdout, 成品.stderr


def 对照():
    if not os.path.isfile(降雨脚本):
        print("对照跑不了：找不到同目录下的降雨.py", file=sys.stderr)
        return 1

    失败 = []
    for 名字, 参数, 期码, 期出, 期错 in 用例:
        头回 = 跑一次(参数)
        二回 = 跑一次(参数)
        if 头回 != 二回:
            失败.append(
                f"{名字}：同一段连跑两次结果不一样，"
                f"头回={头回!r}，二回={二回!r}"
            )
            continue
        实码, 实出, 实错 = 头回
        if (实码, 实出, 实错) != (期码, 期出, 期错):
            失败.append(
                f"{名字}：对不上，"
                f"期望退出码={期码!r} 标准输出={期出!r} 标准错误={期错!r}，"
                f"实际退出码={实码!r} 标准输出={实出!r} 标准错误={实错!r}"
            )

    if 失败:
        for 条 in 失败:
            print(f"对照没过：{条}", file=sys.stderr)
        print(f"共 {len(失败)} 条没过，总共 {len(用例)} 条。", file=sys.stderr)
        return 1

    print(f"全部 {len(用例)} 条对照通过。")
    return 0


if __name__ == "__main__":
    raise SystemExit(对照())
