#!/usr/bin/env python3
# 对照脚本：直接调用同目录的降雨.py，拿它的真输出逐条核对。
# 不在此重写分级；期望值按规格写死，与脚本当前真输出逐字一致。
import subprocess
import sys
from pathlib import Path

脚本路径 = Path(__file__).resolve().parent / "降雨.py"

小雨 = "小雨\n"
中雨 = "中雨\n"
大雨 = "大雨\n"
暴雨 = "暴雨\n"
缺数据 = "没法报雨：缺了降雨量\n"
负数错 = "没法报雨：降雨量不能是负的\n"
别的错 = "没法报雨：请给出一个不小于零的整数降雨量\n"

用例 = [
    ("缺数据：一段都没有", [], 2, "", 缺数据),
    ("缺数据：空着一段", [""], 2, "", 缺数据),
    ("缺数据：写成缺", ["缺"], 2, "", 缺数据),
    ("缺数据：给了两段", ["9", "10"], 2, "", 缺数据),
    ("负数：-5", ["-5"], 2, "", 负数错),
    ("带小数：3.5", ["3.5"], 2, "", 别的错),
    ("带正号：+10", ["+10"], 2, "", 别的错),
    ("夹了字：abc", ["abc"], 2, "", 别的错),
    ("0 是小雨", ["0"], 0, 小雨, ""),
    ("前导零按数值算：009", ["009"], 0, 小雨, ""),
    ("正好9仍是小雨", ["9"], 0, 小雨, ""),
    ("10才升成中雨", ["10"], 0, 中雨, ""),
    ("正好24仍是中雨", ["24"], 0, 中雨, ""),
    ("25才升成大雨", ["25"], 0, 大雨, ""),
    ("正好49仍是大雨", ["49"], 0, 大雨, ""),
    ("50才升成暴雨", ["50"], 0, 暴雨, ""),
    ("50以上也是暴雨：51", ["51"], 0, 暴雨, ""),
]


def 跑一次(参数):
    结果 = subprocess.run(
        [sys.executable, str(脚本路径), *参数],
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    return 结果.returncode, 结果.stdout, 结果.stderr


def main():
    for 名字, 参数, 期望码, 期望出, 期望错 in 用例:
        第一次 = 跑一次(参数)
        第二次 = 跑一次(参数)
        if 第一次 != 第二次:
            print(f"对照没过：{名字}：连跑两次打出来的字不一样：{第一次!r} 对 {第二次!r}")
            return 1
        实际码, 实际出, 实际错 = 第一次
        if (实际码, 实际出, 实际错) != (期望码, 期望出, 期望错):
            print(
                f"对照没过：{名字}：\n"
                f"  实际 退出码={实际码!r} 标准输出={实际出!r} 标准错误={实际错!r}\n"
                f"  期望 退出码={期望码!r} 标准输出={期望出!r} 标准错误={期望错!r}"
            )
            return 1
    print(f"对照全部通过：共 {len(用例)} 条。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
